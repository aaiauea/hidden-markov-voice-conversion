"""HMVC vs established implementations (WORLD, SPTK, librosa) via stored fixtures.

The fixtures were generated by ``tools/generate_feature_reference.py`` in a
separate environment; these tests import only NumPy.  Convention differences
that are intentional are documented in ``tests/data/feature-reference/README.md``
and handled explicitly below.
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

import numpy as np
import pytest

from hmvc.features import AnalysisConfig, FeatureExtractor
from hmvc.features import cepstrum as C
from hmvc.features import envelope as E
from hmvc.features.descriptors import frame_rms, spectral_descriptors, zero_crossing_rate
from hmvc.features.framing import frame_signal, get_window, power_spectrum
from tests._support import feature_signals as S

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "feature-reference"
META = json.loads((DATA / "reference.json").read_text(encoding="utf-8"))
CASES = sorted(META["cases"])
DB = 10.0 / math.log(10.0)                         # ln(power) -> dB


@pytest.fixture(scope="module")
def ref():
    with np.load(DATA / "reference.npz", allow_pickle=False) as z:
        return {k: np.array(z[k]) for k in z.files}


def case_power(ref, name):
    c = META["cases"][name]
    x = ref[f"{name}/x"].astype(np.float64)
    window = get_window("hann", c["frame_length"])
    frames = frame_signal(x, c["frame_length"], c["hop_length"])
    return x, c, window, power_spectrum(frames, window, c["fft_size"])


# -- provenance ---------------------------------------------------------------------


def test_fixture_integrity_and_recipe():
    assert hashlib.sha256((DATA / "reference.npz").read_bytes()).hexdigest() == META["npz_sha256"]
    recipe = (ROOT / "_support" / "feature_signals.py").read_bytes()
    assert hashlib.sha256(recipe).hexdigest() == META["signal_recipe"]["sha256"], \
        "signal recipe changed: regenerate the fixture (see its README)"
    assert META["hmvc_imported"] is False


@pytest.mark.parametrize("name", CASES)
def test_signals_are_reproduced_exactly(ref, name):
    x, f0, fs = S.reference_signals()[name]
    c = META["cases"][name]
    assert fs == c["sample_rate"] and x.size == c["samples"]
    np.testing.assert_array_equal(x.astype(np.float32), ref[f"{name}/x"])
    np.testing.assert_array_equal(S.frame_f0(f0, c["hop_length"]), ref[f"{name}/true_f0"])


def test_geometry_matches_reference_settings():
    for name in CASES:
        c = META["cases"][name]
        g = AnalysisConfig().resolve(c["sample_rate"])
        assert (g.fft_size, g.frame_length, g.mcep_order) == \
            (c["fft_size"], c["frame_length"], c["mcep_order"])
        assert g.mcep_alpha == pytest.approx(c["mcep_alpha"], abs=1e-12)


# -- WORLD CheapTrick ---------------------------------------------------------------------


@pytest.mark.parametrize("name", ["vowel_low", "vowel_high"])
def test_cheaptrick_matches_world(ref, name):
    c = META["cases"][name]
    x = ref[f"{name}/x"].astype(np.float64)
    ours = E.cheaptrick(x, c["sample_rate"], ref[f"{name}/true_f0"], c["hop_length"],
                        c["fft_size"])
    diff = np.abs(DB * (np.log(ours) - ref[f"{name}/cheaptrick_log_sp"].astype(np.float64)))
    assert diff.max() < 1e-3                         # float32 storage of ln(sp)


def test_cheaptrick_matches_world_on_fractional_hop(ref):
    # WORLD's 5 ms grid at 22.05 kHz is fractional (110.25 samples); feed it
    # WORLD's own frame origins to compare the envelope algorithm itself.
    name = "vowel_22k"
    c = META["cases"][name]
    fs = c["sample_rate"]
    x = ref[f"{name}/x"].astype(np.float64)
    f0 = ref[f"{name}/true_f0"]
    origins = np.floor(np.arange(f0.size) * 0.005 * fs + 0.001 + 0.5).astype(np.int64)
    ours = E._cheaptrick_block(x, fs, np.where(f0 > 0, f0, E.DEFAULT_F0), origins,
                               c["fft_size"], -0.15, 1e-12)
    diff = np.abs(DB * (np.log(ours) - ref[f"{name}/cheaptrick_log_sp"].astype(np.float64)))
    assert diff.max() < 1e-3


def test_cheaptrick_matches_world_on_mixed_signal_above_world_floor(ref):
    name = "mixed"
    c = META["cases"][name]
    x = ref[f"{name}/x"].astype(np.float64)
    world = ref[f"{name}/cheaptrick_log_sp"].astype(np.float64)
    ours = E.cheaptrick(x, c["sample_rate"], ref[f"{name}/true_f0"], c["hop_length"],
                        c["fft_size"])
    above = world > math.log(1e-9)                   # WORLD adds a random ~1e-16 floor
    assert above.mean() > 0.6
    assert np.abs(DB * (np.log(ours[above]) - world[above])).max() < 1e-3


# -- SPTK -------------------------------------------------------------------------------------


@pytest.mark.parametrize("name", CASES)
def test_sp2mc_matches_sptk(ref, name):
    c = META["cases"][name]
    sp = np.exp(ref[f"{name}/cheaptrick_log_sp"].astype(np.float64))
    ours = C.sp2mc(sp, c["mcep_order"], c["mcep_alpha"], floor=0.0)  # SPTK applies no floor
    np.testing.assert_allclose(ours, ref[f"{name}/sptk_mcep"], atol=2e-6, rtol=0)


def test_mc2sp_matches_sptk(ref):
    c = META["cases"]["vowel_low"]
    ours = C.mc2sp(ref["vowel_low/sptk_mcep"], c["mcep_alpha"], c["fft_size"])
    diff = np.abs(DB * (np.log(ours) - ref["vowel_low/sptk_mc2sp_log"].astype(np.float64)))
    assert diff.max() < 1e-3


@pytest.mark.parametrize("alpha", [0.0, 0.31, 0.42, 0.55, -0.42])
def test_freqt_matches_sptk(ref, alpha):
    expected = ref[f"freqt/alpha_{alpha:+.2f}"]
    np.testing.assert_allclose(C.freqt(ref["freqt/input"], 30, alpha), expected,
                               atol=1e-12, rtol=0)
    np.testing.assert_allclose(C.freqt_recursive(ref["freqt/input"], 30, alpha), expected,
                               atol=1e-12, rtol=0)


def test_mcep_alpha_matches_sptk(ref):
    for rate, value in zip(ref["mcepalpha/rates"], ref["mcepalpha/values"]):
        assert C.mcep_alpha(int(rate)) == pytest.approx(value, abs=1e-12)


# -- librosa ----------------------------------------------------------------------------------


def test_stft_matches_librosa(ref):
    _, _, window, power = case_power(ref, "vowel_low")
    ours = 0.5 * np.log(np.maximum(power * np.sum(window ** 2), 1e-24))  # undo density scaling
    expected = ref["vowel_low/librosa_log_stft"].astype(np.float64)
    loud = expected > math.log(1e-6)
    np.testing.assert_allclose(ours[loud], expected[loud], atol=1e-5, rtol=0)


@pytest.mark.parametrize("name", CASES)
def test_spectral_descriptors_match_librosa(ref, name):
    _, c, window, power = case_power(ref, name)
    # librosa floors |X|^2 at amin=1e-10; HMVC's power is |X|^2 / sum(w^2)
    d, _ = spectral_descriptors(power, c["sample_rate"],
                                power_floor=1e-10 / np.sum(window ** 2))
    for key in ("centroid", "bandwidth", "rolloff", "flatness"):
        np.testing.assert_allclose(d[key], ref[f"{name}/librosa_{key}"], rtol=1e-9, atol=1e-9,
                                   err_msg=key)


@pytest.mark.parametrize("name", CASES)
def test_rms_and_zcr_match_librosa(ref, name):
    x, c, _, _ = case_power(ref, name)
    length = c["frame_length"]
    frames = frame_signal(x, length, c["hop_length"], left=length // 2)  # librosa: L//2 pad
    np.testing.assert_allclose(frame_rms(frames), ref[f"{name}/librosa_rms"], rtol=1e-6)
    zcr = zero_crossing_rate(frames)
    inner = slice(2, -2)
    assert np.max(np.abs(zcr - ref[f"{name}/librosa_zcr"])[inner]) <= 1.0 / length + 1e-12


# -- F0 accuracy relative to established estimators ------------------------------------------


def _median_cents(f0, truth):
    both = (f0 > 0) & (truth > 0)
    return float(np.median(1200 * np.abs(np.log2(f0[both] / truth[both]))))


@pytest.mark.parametrize("name", CASES)
def test_f0_accuracy_versus_reference_estimators(ref, name):
    c = META["cases"][name]
    x = ref[f"{name}/x"].astype(np.float64)
    truth = ref[f"{name}/true_f0"]
    feats = FeatureExtractor().extract(x, c["sample_rate"])
    ours = _median_cents(feats.f0, truth)
    yin = np.where(truth > 0, ref[f"{name}/librosa_yin"], 0.0)   # librosa YIN has no voicing
    assert ours < _median_cents(yin, truth)                     # better than plain YIN
    assert ours < 2.5
    # no more false voicing than WORLD Harvest
    harvest_false = int(np.sum((ref[f"{name}/harvest_f0"] > 0) & (truth == 0)))
    assert int(np.sum(feats.voiced & (truth == 0))) <= max(harvest_false, 2)
