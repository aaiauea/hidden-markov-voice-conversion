"""Behavioral integration: independent local training, persistence and waveform parity.

Oracles were generated by untouched original HMS with HMVC never imported.
Normal tests consume only local engine code and tiny synthetic reference data.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import pytest
import yaml

from hmvc.engine.core.model import HMSModel
from hmvc.engine.core.synthesizer import SynthesisConfig, Synthesizer
from hmvc.engine.data import wavio
from hmvc.engine.source.hmm import SourceHMMModel
from tests._support.engine_case import train, source_model, renders, render_arrays, score

REFERENCE = Path(__file__).parent / "data/hms-reference"
META = json.loads((REFERENCE / "reference.json").read_text(encoding="utf-8"))
CASES = sorted(META["cases"])


def assert_array(actual, expected):
    assert actual.shape == expected.shape
    if actual.dtype.kind in "fci" and expected.dtype.kind in "fci":
        np.testing.assert_allclose(actual, expected, rtol=1e-10, atol=1e-12, equal_nan=True)
    else:
        np.testing.assert_array_equal(actual, expected)


def assert_document(actual, expected):
    """Compare complete model metadata, tolerating numerical roundoff only."""
    if isinstance(expected, dict):
        assert actual.keys() == expected.keys()
        for key in expected:
            assert_document(actual[key], expected[key])
    elif isinstance(expected, list):
        assert len(actual) == len(expected)
        for left, right in zip(actual, expected):
            assert_document(left, right)
    elif isinstance(expected, float):
        assert actual == pytest.approx(expected, rel=1e-10, abs=1e-12)
    else:
        assert actual == expected


def assert_saved_model(directory, reference):
    assert {p.name for p in directory.iterdir()} == {p.name for p in reference.iterdir()}
    for path in reference.iterdir():
        if path.suffix == ".npz":
            with np.load(path, allow_pickle=False) as expected, np.load(directory / path.name, allow_pickle=False) as actual:
                assert set(actual.files) == set(expected.files)
                for key in expected.files:
                    assert_array(actual[key], expected[key])
        else:
            assert_document(yaml.safe_load((directory / path.name).read_text()), yaml.safe_load(path.read_text()))


def assert_render(name, result):
    arrays = render_arrays(result)
    expected_keys = {key.split("/", 1)[1] for key in META["array_keys"] if key.startswith(name + "/")}
    assert set(arrays) == expected_keys
    with np.load(REFERENCE / "renders.npz", allow_pickle=False) as expected:
        for field, actual in arrays.items():
            assert_array(np.asarray(actual), expected[META["array_keys"][name + "/" + field]])
    record = META["cases"][name]
    assert result.diagnostics == record["diagnostics"]
    assert len(result.audio) == record["samples"]
    assert len(result.params.f0) == record["frames"]
    assert np.isfinite(result.audio).all() and np.max(np.abs(result.audio)) > 0.01
    assert (result.source.n_units if result.source else 0) == record["source_units"]


